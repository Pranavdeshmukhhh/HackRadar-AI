import logging
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from datetime import datetime, timezone, timedelta
from typing import List, Dict, Any, Optional
import requests

from .models import HackathonEvent

logger = logging.getLogger(__name__)


class GitHubIssueNotifier:
    """Dispatches alerts as new GitHub Issues with automated labels."""

    def __init__(self, token: Optional[str] = None, repository: Optional[str] = None):
        self.token = token or os.getenv("GITHUB_TOKEN")
        self.repository = repository or os.getenv("GITHUB_REPOSITORY")

    @property
    def is_configured(self) -> bool:
        return bool(self.token and self.repository)

    def send_alert(self, event: HackathonEvent) -> bool:
        if not self.is_configured:
            logger.debug("GitHub Issue notifier skipped: GITHUB_TOKEN or GITHUB_REPOSITORY not set")
            return False

        url = f"https://api.github.com/repos/{self.repository}/issues"
        headers = {
            "Authorization": f"Bearer {self.token}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
        }

        # Dynamic labels
        labels = ["hackathon-alert"]
        if event.solo_allowed:
            labels.append("solo-friendly")
        if event.is_nagpur_local:
            labels.append("nagpur-local")
        if event.is_maharashtra:
            labels.append("maharashtra")
        if event.mode.lower() in ("online", "virtual"):
            labels.append("online")

        title_prefix = "📍 [NAGPUR]" if event.is_nagpur_local else "🚀 [ALERT]"
        issue_title = f"{title_prefix} {event.title} ({event.source}) - Score {event.score}/100"

        body = f"""# {event.title}

{event.summary_markdown()}

---
*Auto-generated by Nagpur Hackathon Monitor | [View Dashboard](HACKATHONS.md)*
"""

        payload = {
            "title": issue_title,
            "body": body,
            "labels": labels,
        }

        try:
            resp = requests.post(url, headers=headers, json=payload, timeout=15)
            if resp.status_code in (200, 201):
                issue_url = resp.json().get("html_url")
                logger.info(f"Successfully opened GitHub Issue for '{event.title}': {issue_url}")
                return True
            else:
                logger.error(f"Failed to open GitHub Issue: HTTP {resp.status_code} - {resp.text}")
                return False
        except Exception as e:
            logger.error(f"Exception opening GitHub Issue: {e}")
            return False


class DiscordNotifier:
    """Dispatches rich embed notifications to a Discord channel webhook."""

    def __init__(self, webhook_url: Optional[str] = None):
        self.webhook_url = webhook_url or os.getenv("DISCORD_WEBHOOK_URL")

    @property
    def is_configured(self) -> bool:
        return bool(self.webhook_url and self.webhook_url.startswith("http"))

    def send_alert(self, event: HackathonEvent) -> bool:
        if not self.is_configured:
            return False

        # Color: Gold for Nagpur local (0xF59E0B), Purple for Solo/AI (0x8B5CF6), Blue standard (0x3B82F6)
        color = 0xF59E0B if event.is_nagpur_local else 0x8B5CF6 if event.solo_allowed else 0x3B82F6

        embed = {
            "title": f"🎯 {event.title}",
            "url": event.url,
            "description": event.description[:250] + ("..." if len(event.description) > 250 else ""),
            "color": color,
            "fields": [
                {"name": "⭐ Priority Score", "value": f"**{event.score}/100**", "inline": True},
                {"name": "👤 Participation", "value": event.solo_badge, "inline": True},
                {"name": "🌐 Mode & Venue", "value": f"{event.mode} • {event.venue or 'TBA'}", "inline": True},
                {"name": "⏰ Deadline", "value": str(event.registration_deadline or 'Check link'), "inline": True},
                {"name": "🏆 Prize Pool", "value": event.prize_pool, "inline": True},
                {"name": "🏢 Source", "value": event.source, "inline": True},
                {
                    "name": "🎯 Match Reasons",
                    "value": "\n".join(f"• {r}" for r in event.matched_reasons) or "Standard Match",
                    "inline": False,
                },
            ],
            "footer": {"text": "Nagpur Hackathon Monitor • Automated Discovery"},
            "timestamp": datetime.now(timezone.utc).isoformat(),
        }

        payload = {"embeds": [embed]}
        try:
            resp = requests.post(self.webhook_url, json=payload, timeout=10)
            return resp.status_code in (200, 204)
        except Exception as e:
            logger.error(f"Discord webhook error: {e}")
            return False


class TelegramNotifier:
    """Dispatches Telegram notifications to a target chat or channel."""

    def __init__(self, bot_token: Optional[str] = None, chat_id: Optional[str] = None):
        self.bot_token = bot_token or os.getenv("TELEGRAM_BOT_TOKEN")
        self.chat_id = chat_id or os.getenv("TELEGRAM_CHAT_ID")

    @property
    def is_configured(self) -> bool:
        return bool(self.bot_token and self.chat_id)

    def send_alert(self, event: HackathonEvent) -> bool:
        if not self.is_configured:
            return False

        reasons = "\n".join(f"▫️ {r}" for r in event.matched_reasons)
        text = (
            f"<b>🚀 New Hackathon Match Found!</b>\n\n"
            f"<b>Title:</b> <a href=\"{event.url}\">{event.title}</a>\n"
            f"<b>Source:</b> {event.source} | <b>Score:</b> {event.score}/100\n"
            f"<b>Venue / Mode:</b> {event.venue} ({event.mode})\n"
            f"<b>Participation:</b> {event.solo_badge}\n"
            f"<b>Deadline:</b> {event.registration_deadline or 'Check site'}\n"
            f"<b>Prize Pool:</b> {event.prize_pool}\n\n"
            f"<b>Match Reasons:</b>\n{reasons}\n\n"
            f"👉 <a href=\"{event.url}\">Register Here</a>"
        )

        url = f"https://api.telegram.org/bot{self.bot_token}/sendMessage"
        payload = {
            "chat_id": self.chat_id,
            "text": text,
            "parse_mode": "HTML",
            "disable_web_page_preview": False,
        }

        try:
            resp = requests.post(url, json=payload, timeout=10)
            return resp.status_code == 200
        except Exception as e:
            logger.error(f"Telegram alert error: {e}")
            return False


class EmailNotifier:
    """Dispatches HTML email notifications via SMTP."""

    def __init__(self):
        port_raw = os.getenv("SMTP_PORT") or "587"
        try:
            self.port = int(str(port_raw).strip())
        except (ValueError, TypeError):
            self.port = 587
        self.user = os.getenv("SMTP_USER")
        self.password = os.getenv("SMTP_PASSWORD")
        self.receiver = os.getenv("ALERT_RECEIVER_EMAIL")

    @property
    def is_configured(self) -> bool:
        return bool(self.host and self.user and self.password and self.receiver)

    def send_alert(self, event: HackathonEvent) -> bool:
        if not self.is_configured:
            return False

        msg = MIMEMultipart("alternative")
        msg["Subject"] = f"🎯 [Hackathon Alert] {event.title} - Score: {event.score}/100"
        msg["From"] = self.user
        msg["To"] = self.receiver

        html_body = f"""
        <html>
        <body style="font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; color: #1e293b; max-width: 600px; margin: 0 auto; padding: 20px;">
            <div style="background: linear-gradient(135deg, #1e293b 0%, #0f172a 100%); color: #ffffff; padding: 20px; border-radius: 8px 8px 0 0;">
                <h2 style="margin: 0; color: #38bdf8;">Nagpur Hackathon Monitor</h2>
                <p style="margin: 5px 0 0; color: #94a3b8; font-size: 14px;">High Priority Opportunity Discovered</p>
            </div>
            <div style="border: 1px solid #e2e8f0; border-top: none; padding: 24px; border-radius: 0 0 8px 8px; background: #ffffff;">
                <h1 style="font-size: 20px; margin-top: 0;"><a href="{event.url}" style="color: #2563eb; text-decoration: none;">{event.title}</a></h1>
                <table style="width: 100%; border-collapse: collapse; margin: 16px 0;">
                    <tr><td style="padding: 6px 0; color: #64748b; font-size: 14px;">Score:</td><td style="font-weight: bold; color: #059669;">{event.score} / 100</td></tr>
                    <tr><td style="padding: 6px 0; color: #64748b; font-size: 14px;">Source:</td><td>{event.source}</td></tr>
                    <tr><td style="padding: 6px 0; color: #64748b; font-size: 14px;">Mode & Venue:</td><td>{event.mode} ({event.venue})</td></tr>
                    <tr><td style="padding: 6px 0; color: #64748b; font-size: 14px;">Participation:</td><td>{event.solo_badge}</td></tr>
                    <tr><td style="padding: 6px 0; color: #64748b; font-size: 14px;">Deadline:</td><td>{event.registration_deadline or 'Check portal'}</td></tr>
                    <tr><td style="padding: 6px 0; color: #64748b; font-size: 14px;">Prize Pool:</td><td>{event.prize_pool}</td></tr>
                </table>
                <div style="margin: 20px 0;">
                    <a href="{event.url}" style="background-color: #2563eb; color: #ffffff; padding: 12px 24px; text-decoration: none; border-radius: 6px; font-weight: bold; display: inline-block;">Register Official Link</a>
                </div>
            </div>
        </body>
        </html>
        """
        msg.attach(MIMEText(html_body, "html"))

        try:
            with smtplib.SMTP(self.host, self.port) as server:
                server.starttls()
                server.login(self.user, self.password)
                server.send_message(msg)
                logger.info(f"Email alert sent to {self.receiver} for {event.title}")
                return True
        except Exception as e:
            logger.error(f"SMTP error sending email: {e}")
            return False


class DashboardNotifier:
    """Generates and updates the live HACKATHONS.md repository dashboard."""

    def __init__(self, output_path: str = "HACKATHONS.md"):
        self.output_path = output_path

    def update_dashboard(self, events: List[HackathonEvent]) -> str:
        # IST is UTC+5:30
        ist_offset = timezone(timedelta(hours=5, minutes=30))
        now_ist = datetime.now(ist_offset).strftime("%Y-%m-%d %I:%M %p IST")
        now_utc = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

        nagpur_count = sum(1 for e in events if e.is_nagpur_local)
        solo_count = sum(1 for e in events if e.solo_allowed)
        online_count = sum(1 for e in events if e.mode.lower() in ("online", "virtual"))
        high_priority_count = sum(1 for e in events if e.score >= 60)

        markdown = f"""# 🚀 Nagpur AI & Software Hackathon Live Dashboard

> **Automated Hackathon Monitor** tracking open hackathons across **Unstop**, **Devfolio**, and **Devpost** with intelligent scoring prioritizing **Nagpur/Vidarbha regional venues**, **Solo eligibility**, and **AI/Software tracks**.

---

### 📊 Quick Metrics
| Total Qualified | 📍 Nagpur Local | 👤 Solo-Friendly | 🌐 Online/Virtual | ⭐ High Priority (60+ pts) |
|:---:|:---:|:---:|:---:|:---:|
| **{len(events)}** | **{nagpur_count}** | **{solo_count}** | **{online_count}** | **{high_priority_count}** |

*Last Updated:* **{now_ist}** (`{now_utc}`)

---

## 🏆 Top Qualified Hackathons
"""

        if not events:
            markdown += "\n*No active hackathons currently match the qualifying criteria. Next check scheduled daily at 8:00 AM IST.*\n"
        else:
            markdown += """
| Score | Title | Mode / Venue | Solo? | Deadline | Tracks | Source | Action |
|:---:|:---|:---|:---:|:---|:---|:---:|:---:|
"""
            for e in events:
                tracks_preview = ", ".join(e.tracks[:2]) if e.tracks else "AI / Software"
                if len(tracks_preview) > 28:
                    tracks_preview = tracks_preview[:25] + "..."

                solo_tag = "✅ Solo" if e.solo_allowed else "👥 Team"
                loc_tag = "📍 **Nagpur**" if e.is_nagpur_local else ("🌐 Online" if e.mode.lower() == "online" else f"🏢 {e.venue[:15]}")
                title_clean = e.title.replace("|", "-")
                score_badge = f"**`{e.score}`**"

                markdown += (
                    f"| {score_badge} | [{title_clean}]({e.url}) | {loc_tag} | {solo_tag} | "
                    f"`{e.registration_deadline or 'TBA'}` | {tracks_preview} | {e.source} | "
                    f"[Register]({e.url}) |\n"
                )

            markdown += "\n---\n\n## 📋 Detailed Event Breakdowns\n\n"
            for idx, e in enumerate(events, 1):
                reasons_str = " • ".join(e.matched_reasons)
                markdown += f"""### {idx}. [{e.title}]({e.url})
- **Platform:** `{e.source}` | **Priority Score:** `{e.score}/100` | **Mode:** `{e.mode}`
- **Venue / Location:** {e.location_badge}
- **Participation:** {e.solo_badge}
- **Registration Deadline:** `{e.registration_deadline or 'Refer to portal'}`
- **Prize Pool:** `{e.prize_pool}`
- **Tracks:** {', '.join(e.tracks) if e.tracks else 'General / Open Innovation'}
- **Organizer:** {e.organizer}
- **Match Factors:** {reasons_str}

👉 **[Direct Link to Apply]({e.url})**

---
"""

        markdown += """
### ⚙️ How Scoring Works
- **📍 Nagpur & Vidarbha Boost (+45 pts):** Matches Nagpur, Vidarbha, VNIT, IIIT Nagpur, IIM Nagpur, RCOEM/RBU, YCCE, GHRCE, Symbiosis Nagpur.
- **🏢 Maharashtra Proximity (+25 pts):** Matches Pune, Mumbai, Nashik, and other Maharashtra universities.
- **🌐 Online / Hybrid Mode (+15 pts):** Readily accessible without physical travel constraints.
- **👤 Solo Participation (+35 pts):** Verified `min_team_size <= 1` so you can participate alone.
- **🤖 AI & Software Track (+25 pts):** Matches Artificial Intelligence, GenAI, LLMs, Agents, Software, Full Stack.

---
*Built with ❤️ for Nagpur developers, hackers, and builders.*
"""

        with open(self.output_path, "w", encoding="utf-8") as f:
            f.write(markdown)

        logger.info(f"Dashboard successfully generated at {self.output_path}")
        return markdown


class NotificationManager:
    """Coordinates alerts across all configured channels."""

    def __init__(self, config: Dict[str, Any]):
        self.config = config
        notif_cfg = config.get("notifiers", {})

        self.github_notifier = GitHubIssueNotifier() if notif_cfg.get("github_issues", {}).get("enabled", True) else None
        self.discord_notifier = DiscordNotifier() if notif_cfg.get("discord", {}).get("enabled", True) else None
        self.telegram_notifier = TelegramNotifier() if notif_cfg.get("telegram", {}).get("enabled", True) else None
        self.email_notifier = EmailNotifier() if notif_cfg.get("smtp", {}).get("enabled", True) else None
        self.dashboard_notifier = DashboardNotifier(output_path=notif_cfg.get("dashboard", {}).get("output_path", "HACKATHONS.md"))

    def dispatch_all(self, new_events: List[HackathonEvent], is_dry_run: bool = False) -> Dict[str, int]:
        """Dispatch notifications for all new events to active channels."""
        counts = {"github": 0, "discord": 0, "telegram": 0, "email": 0}

        if is_dry_run:
            logger.info(f"[DRY-RUN] Would notify {len(new_events)} new hackathons to configured channels")
            return counts

        for event in new_events:
            if self.github_notifier and self.github_notifier.send_alert(event):
                counts["github"] += 1
            if self.discord_notifier and self.discord_notifier.send_alert(event):
                counts["discord"] += 1
            if self.telegram_notifier and self.telegram_notifier.send_alert(event):
                counts["telegram"] += 1
            if self.email_notifier and self.email_notifier.send_alert(event):
                counts["email"] += 1

        return counts

    def update_dashboard(self, events: List[HackathonEvent]) -> str:
        """Regenerate HACKATHONS.md dashboard."""
        return self.dashboard_notifier.update_dashboard(events)
